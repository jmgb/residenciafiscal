import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const frontendDir = resolve(scriptDir, '..');
const routesFile = join(frontendDir, 'src/data/countryRoutes.json');
const redirectsFile = join(frontendDir, 'public/_redirects');
const routes = JSON.parse(readFileSync(routesFile, 'utf8'));

const legacyRedirects = routes.flatMap((route) => {
  const legacyPath = `/${route.name.toLowerCase().replace(/\s+/g, '-')}`;
  return legacyPath === route.path ? [] : [`${encodeURI(legacyPath)} ${route.path} 301!`];
});

const countryRewrites = routes.map((route) => `${route.path} ${route.path}/index.html 200!`);

const contents = [
  '# Generated by frontend/scripts/build-netlify-redirects.mjs.',
  '# Source: frontend/src/data/countryRoutes.json.',
  ...legacyRedirects,
  ...countryRewrites,
  '',
].join('\n');

writeFileSync(redirectsFile, contents, 'utf8');
console.log(`[netlify] Generated ${redirectsFile}`);
