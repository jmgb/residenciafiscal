import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const frontendDir = resolve(scriptDir, '..');
const routesFile = join(frontendDir, 'src/data/countryRoutes.json');
const jurisdictionsFile = join(frontendDir, 'src/data/jurisdictions.json');
const normativaFile = join(frontendDir, 'public/data/normativa.json');
const redirectsFile = join(frontendDir, 'public/_redirects');
const routes = JSON.parse(readFileSync(routesFile, 'utf8'));
// El nombre ya no vive en `countryRoutes.json`: sale del catálogo compartido,
// que es lo que genera `src/export_frontend_projections.py`.
const { jurisdictions } = JSON.parse(readFileSync(jurisdictionsFile, 'utf8'));
const normativa = JSON.parse(readFileSync(normativaFile, 'utf8'));
// Solo las sentencias que este build ha materializado. Sin regla y sin fichero,
// el fallback de `netlify.toml` devuelve un 404 real, que es justo lo que debe
// pasar en producción con un borrador interno.
const sentenciasFile = join(frontendDir, 'public/data/sentencias.json');
const sentencias = existsSync(sentenciasFile)
  ? JSON.parse(readFileSync(sentenciasFile, 'utf8'))
  : { judgments: [] };

// `/estados-unidos` responde también a `/estados unidos` escrito con el nombre:
// son las URL que circularon antes de fijar la política de slugs.
const legacyRedirects = routes.flatMap((route) => {
  const legacyPath = `/${jurisdictions[route.code].name.toLowerCase().replace(/\s+/g, '-')}`;
  return legacyPath === route.path ? [] : [`${encodeURI(legacyPath)} ${route.path} 301!`];
});

const countryRewrites = routes.map((route) => `${route.path} ${route.path}/index.html 200!`);

// Las fichas de precepto y su índice también sirven su copia prerenderizada;
// sin regla propia, el fallback 404 de netlify.toml las mataría si el fichero
// físico no ganara por cualquier motivo.
const normativaRewrites = [
  '/espana/normativa /espana/normativa/index.html 200!',
  ...normativa.map(
    (entry) => `/espana/normativa/${entry.slug} /espana/normativa/${entry.slug}/index.html 200!`
  ),
];

const sentenciaRewrites =
  sentencias.judgments.length === 0
    ? []
    : [
        '/espana/sentencias /espana/sentencias/index.html 200!',
        ...sentencias.judgments.map(
          (entry) =>
            `/espana/sentencias/${entry.judgmentId} /espana/sentencias/${entry.judgmentId}/index.html 200!`
        ),
      ];

const contents = [
  '# Generated by frontend/scripts/build-netlify-redirects.mjs.',
  '# Source: countryRoutes.json + jurisdictions.json + public/data/normativa.json.',
  ...legacyRedirects,
  ...countryRewrites,
  ...normativaRewrites,
  ...sentenciaRewrites,
  '',
].join('\n');

writeFileSync(redirectsFile, contents, 'utf8');
console.log(`[netlify] Generated ${redirectsFile}`);
